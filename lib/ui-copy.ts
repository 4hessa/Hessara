export const language = (locale: Locale) => (ar: string, en: string) => {
  if (locale === 'ar') return ar;
  const key = baseKeys.get(en);
  return localized[locale]?.[en] ?? (key ? dictionaries[locale]?.[key] : undefined) ?? en;
};
