"""Trusted control plane for a DEDICATED Linux Docker host, never Vercel.

Only this process can reach Docker and the platform. Engine containers receive
neither the Docker socket nor platform credentials and have no network devices.
"""
from __future__ import annotations

import argparse
from collections import deque
import json
import os
from pathlib import Path
import random
import re
import shutil
import signal
import sys
import tempfile
import threading
import time
import urllib.error
import urllib.parse
import urllib.request

from common import MAX_RESULT, MAX_UPLOAD, WorkerError, bounded_process, hash_file
from verification import load_verification

STOP = threading.Event()
IMAGE_DIGEST = re.compile(r'^[a-zA-Z0-9./:_-]+@sha256:[a-f0-9]{64}$')
IDENTIFIER = re.compile(r'^[a-zA-Z0-9_-]{1,80}$')


def sanitized_log(data: bytes) -> str:
    return re.sub(r'[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]', '', data.decode(errors='replace'))[:1000]


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise WorkerError('unsafe_download', 'Artifact redirects are forbidden.')


def secure_url(url: str, hosts: set[str]) -> str:
    parsed = urllib.parse.urlsplit(url)
    if (parsed.scheme != 'https' or parsed.hostname not in hosts or parsed.username
            or parsed.password or parsed.port not in (None, 443) or parsed.fragment):
        raise WorkerError('unsafe_download', 'Download origin is outside the configured storage allowlist.')
    return url


def download(artifact: dict, target: Path, hosts: set[str]) -> None:
    size = artifact.get('sizeBytes')
    digest = artifact.get('sha256', '')
    if not isinstance(size, int) or not 0 < size <= MAX_UPLOAD or not re.fullmatch(r'[a-f0-9]{64}', digest):
        raise WorkerError('invalid_artifact', 'Invalid artifact size or digest.')
    request = urllib.request.Request(secure_url(artifact['downloadUrl'], hosts), headers={'Accept': 'application/octet-stream'})
    opener = urllib.request.build_opener(NoRedirect)
    consumed = 0
    deadline = time.monotonic() + 30
    with opener.open(request, timeout=20) as response, target.open('xb') as output:
        while True:
            if STOP.is_set():
                raise WorkerError('cancelled', 'Worker is shutting down.')
            if time.monotonic() > deadline:
                raise WorkerError('download_timeout', 'Artifact transfer exceeded the bounded download deadline.')
            chunk = response.read(65536)
            if not chunk:
                break
            consumed += len(chunk)
            if consumed > size or consumed > MAX_UPLOAD:
                raise WorkerError('invalid_artifact', 'Artifact length exceeds its registered size.')
            output.write(chunk)
    if consumed != size or hash_file(target) != digest:
        raise WorkerError('integrity_mismatch', 'Artifact digest or length does not match the registered upload.')
    target.chmod(0o444)


def hardening(config: dict, *, name: str, worker_id: str, artifact: Path | None = None) -> list[str]:
    if not IMAGE_DIGEST.fullmatch(config.get('image', '')):
        raise WorkerError('image_unpinned', 'Engine image must use a verified SHA-256 digest.')
    args = ['docker', 'create', '--name', name, '--label', f'hessara.re.worker={worker_id}',
            '--network', 'none', '--read-only', '--user', '10001:10001',
            '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges:true',
            '--pids-limit', '256', '--cpus', str(config['cpu']),
            '--memory', f'{config["memoryMb"]}m', '--memory-swap', f'{config["memoryMb"]}m',
            '--ulimit', 'nofile=2048:2048', '--ulimit', 'core=0:0',
            '--log-driver', 'none', '--stop-timeout', '3',
            '--tmpfs', '/tmp:rw,noexec,nosuid,nodev,size=64m,uid=10001,gid=10001,mode=1770',
            '--tmpfs', f'/work:rw,noexec,nosuid,nodev,size={config["diskMb"]}m,uid=10001,gid=10001,mode=0700',
            '--env', 'HOME=/work', '--env', 'TMPDIR=/tmp', '--env', 'PYTHONDONTWRITEBYTECODE=1',
            '--env', 'HESSARA_RE_CONTAINER=1']
    if artifact:
        args += ['--mount', f'type=bind,src={artifact},dst=/input/artifact,readonly']
    return args


def docker_command(args, timeout=15):
    output, error, status = bounded_process(args, timeout, limit=65536)
    if status:
        raise WorkerError('container_failure', error.decode(errors='replace')[:1000])
    return output


def cleanup_container(name: str):
    # Deterministic name is generated by us. No artifact-derived shell text.
    try:
        docker_command(['docker', 'rm', '--force', name])
    except WorkerError:
        # A create may have completed in the daemon after its client timed out.
        # A failed rm is harmless ONLY when a successful daemon query proves absence.
        remaining = docker_command(['docker', 'ps', '--all', '--quiet', '--filter', 'name=^/' + re.escape(name) + '$'])
        if remaining.strip():
            raise WorkerError('cleanup_failed', 'Container removal could not be verified.')


def classify_failure(error: Exception, stage: str) -> tuple[str, bool]:
    """Retry only safe transfer faults before any container execution began."""
    if stage == 'download':
        if isinstance(error, urllib.error.HTTPError):
            if error.code in {408, 429, 500, 502, 503, 504}:
                return 'STORAGE_TEMPORARY', True
        elif (isinstance(error, (urllib.error.URLError, TimeoutError))
              or isinstance(error, WorkerError) and error.code == 'download_timeout'):
            return 'NETWORK_TEMPORARY', True
    raw = error.code if isinstance(error, WorkerError) else 'worker_failure'
    return {'cancelled': 'CANCELLED', 'timed_out': 'TIMEOUT'}.get(raw, raw.upper()), False


def host_capacity() -> dict:
    memory = 0
    try:
        for line in Path('/proc/meminfo').read_text().splitlines():
            if line.startswith('MemAvailable:'):
                memory = int(line.split()[1]) // 1024
    except (OSError, ValueError):
        pass
    return dict(slots=1, cpuCount=os.cpu_count() or 1, availableMemoryMb=memory,
                diskFreeMb=shutil.disk_usage(tempfile.gettempdir()).free // 1048576)


def container_metrics(name: str) -> dict:
    """Docker's actual point-in-time observations, not fabricated progress."""
    raw = json.loads(docker_command(['docker', 'stats', '--no-stream', '--format', '{{json .}}', name], timeout=8))
    metrics = {}
    try:
        metrics['cpuPercent'] = float(raw['CPUPerc'].rstrip('%'))
        match = re.match(r'^([0-9.]+)\s*([KMG]?i?B)', raw['MemUsage'])
        if match:
            scale = {'B': 1 / 1048576, 'kB': 1 / 1024, 'KB': 1 / 1024,
                     'KiB': 1 / 1024, 'MB': 1, 'MiB': 1, 'GB': 1024, 'GiB': 1024}
            metrics['memoryMb'] = float(match[1]) * scale.get(match[2], 1)
    except (KeyError, ValueError):
        raise WorkerError('invalid_metrics', 'Container metrics were not readable.')
    return metrics


class Client:
    def __init__(self):
        self.origin = os.environ.get('HESSARA_RE_PLATFORM_URL', '').rstrip('/')
        parsed = urllib.parse.urlsplit(self.origin)
        if parsed.scheme != 'https' or not parsed.hostname or parsed.path not in ('', '/'):
            raise WorkerError('configuration_error', 'Platform URL must be an HTTPS origin.')
        self.token = os.environ.get('HESSARA_RE_WORKER_TOKEN', '')
        if len(self.token) < 32:
            raise WorkerError('configuration_error', 'Worker token must contain at least 32 characters.')
        self.opener = urllib.request.build_opener(NoRedirect)

    def request(self, action: str, **payload) -> dict:
        body = json.dumps(dict(action=action, **payload), ensure_ascii=False).encode()
        if len(body) > 2 * 1024 * 1024:
            raise WorkerError('output_limit', 'Worker API payload exceeds policy.')
        req = urllib.request.Request(self.origin + '/api/reverse-engineering/worker', data=body,
                                     headers={'Authorization': 'Bearer ' + self.token,
                                              'Content-Type': 'application/json'}, method='POST')
        with self.opener.open(req, timeout=20) as response:
            data = response.read(2 * 1024 * 1024 + 1)
            if len(data) > 2 * 1024 * 1024:
                raise WorkerError('invalid_response', 'Worker API reply exceeds policy.')
            result = json.loads(data)
            if not isinstance(result, dict):
                raise WorkerError('invalid_response', 'Invalid worker API response.')
            return result


class Supervisor:
    def __init__(self, config_path: Path):
        self.worker_id = os.environ.get('HESSARA_RE_WORKER_ID', 'dedicated-worker-1')
        if not IDENTIFIER.fullmatch(self.worker_id):
            raise WorkerError('configuration_error', 'Worker identifier is invalid.')
        self.config = json.loads(config_path.read_text(encoding='utf-8-sig'))
        self.health_cache = None
        self.health_at = 0.0
        self.client = Client()
        self.storage_hosts = set(filter(None, os.environ.get('HESSARA_RE_STORAGE_HOSTS', '').split(',')))
        if not self.storage_hosts:
            raise WorkerError('configuration_error', 'Storage host allowlist is required.')

    def recover(self):
        names = docker_command(['docker', 'ps', '-a', '--filter', f'label=hessara.re.worker={self.worker_id}',
                                '--format', '{{.Names}}']).decode().splitlines()
        for name in names:
            if name.startswith('hessara-re-'):
                cleanup_container(name)

    def health(self) -> list[dict]:
        if self.health_cache is not None and time.monotonic() - self.health_at < 60:
            return self.health_cache
        records = []
        capacity = host_capacity()
        for engine, config in self.config.items():
            record = dict(id=engine, healthy=False, enabled=config.get('enabled') is True, capacity=0,
                          capabilities=config['capabilities'], reason=config['reason'])
            if not config.get('enabled'):
                record['reasonCode'] = 'ENGINE_DISABLED'
                records.append(record)
                continue
            if not config.get('benchmarkApproved'):
                record.update(reasonCode='BENCHMARK_REQUIRED', reason='Resource benchmarks have not been approved.')
                records.append(record)
                continue
            if not IMAGE_DIGEST.fullmatch(config.get('image', '')):
                record.update(reasonCode='IMAGE_UNPINNED', reason='An immutable verified engine image is required.')
                records.append(record)
                continue
            if not load_verification(config, engine):
                record.update(reasonCode='VERIFIED_SAMPLE_REQUIRED', reason='A successful real sample analysis report is required.')
                records.append(record)
                continue
            if capacity['availableMemoryMb'] < config['memoryMb'] + 1024 or capacity['diskFreeMb'] < config['diskMb'] + 1024:
                record.update(reasonCode='INSUFFICIENT_CAPACITY', reason='Worker has insufficient measured free resources.')
                records.append(record)
                continue
            name = 'hessara-re-health-' + engine + '-' + self.worker_id
            create_attempted = False
            try:
                args = hardening(config, name=name, worker_id=self.worker_id)
                create_attempted = True
                docker_command(args + [config['image'], '--health'])
                output = docker_command(['docker', 'start', '--attach', name], timeout=45)
                data = json.loads(output)
                version = data.get('version', '').strip() if isinstance(data.get('version'), str) else ''
                proof = load_verification(config, engine, version) if version else None
                if data.get('healthy') is True and version and proof:
                    record.update(healthy=True, capacity=1, version=version, verification=proof, reason=None, reasonCode=None)
                else:
                    record.update(reasonCode='HEALTH_CHECK_FAILED', reason='Engine version or verified sample no longer matches.')
            except (WorkerError, ValueError, OSError):
                record.update(reasonCode='HEALTH_CHECK_FAILED', reason='Engine container or installation is unavailable.')
            finally:
                if create_attempted:
                    try:
                        cleanup_container(name)
                    except WorkerError:
                        STOP.set()
                        raise
            records.append(record)
        self.health_cache, self.health_at = records, time.monotonic()
        return records

    def execute(self, claimed: dict):
        job = claimed['job']
        job_id = job['id']
        if not IDENTIFIER.fullmatch(job_id):
            raise WorkerError('invalid_job', 'Invalid job identifier.')
        lease = dict(workerId=self.worker_id, jobId=job_id, leaseToken=claimed['leaseToken'])
        engine = job['engineId']
        config = self.config.get(engine)
        name = 'hessara-re-' + job_id
        create_attempted = False
        stage = 'validating'
        started = time.monotonic()
        outcome = None
        logs = deque(maxlen=20)
        observed_memory = 0.0
        monitor_stop = threading.Event()
        cancel_requested = threading.Event()
        monitor_failed = threading.Event()
        monitor = None
        try:
            if not config or not config.get('enabled') or not config.get('benchmarkApproved'):
                raise WorkerError('engine_unavailable', 'Engine is disabled on this worker.')
            proof = load_verification(config, engine, job.get('expectedEngineVersion'))
            if (not proof or proof['imageDigest'] != job.get('expectedImageDigest')
                    or proof['engineVersion'] != job.get('expectedEngineVersion')):
                raise WorkerError('engine_unavailable', 'The leased engine verification no longer matches this worker.')
            if host_capacity()['availableMemoryMb'] < config['memoryMb'] + 1024:
                raise WorkerError('capacity_exhausted', 'Worker no longer has sufficient free resources.')
            with tempfile.TemporaryDirectory(prefix='hessara-re-') as directory:
                root = Path(directory)
                root.chmod(0o711)
                artifact = root / 'artifact'
                self.client.request('heartbeat', **lease, stage='validating', metrics={}, capacity=host_capacity())
                # Parsers (including ZIP/ASAR) run ONLY in the engine container.
                stage = 'download'
                download(job['artifact'], artifact, self.storage_hosts)
                stage = 'validating'
                self.client.request('heartbeat', **lease, stage='validating', metrics={}, capacity=host_capacity())
                # Download/startup count against the same absolute API job deadline;
                # reserve ten seconds for verified container removal/publication.
                timeout = min(int(job.get('timeoutSeconds', config['timeoutSeconds'])), config['timeoutSeconds']) - int(time.monotonic() - started) - 10
                if timeout < 1:
                    raise WorkerError('invalid_job', 'Invalid execution deadline.')
                args = hardening(config, name=name, worker_id=self.worker_id, artifact=artifact)
                command = [config['image'], '--engine', engine, '--format', job['artifact']['format'],
                           '--options', json.dumps(job.get('options', {})), '--timeout', str(timeout)]
                create_attempted = True
                stage = 'container-create'
                docker_command(args + command)
                stage = 'running'
                self.client.request('heartbeat', **lease, stage='running', metrics={}, capacity=host_capacity())

                def monitor_job():
                    nonlocal observed_memory
                    # Network/storage control calls never block the wall-clock
                    # watchdog. The process loop reads only these thread events.
                    while not monitor_stop.wait(10):
                        # Fail closed if the lease cannot be refreshed. Never continue
                        # expensive analysis after losing the control-plane connection.
                        try:
                            try:
                                metrics = container_metrics(name)
                            except (WorkerError, ValueError):
                                # A fast-completing container may exit during stats.
                                metrics = {}
                            observed_memory = max(observed_memory, metrics.get('memoryMb', 0))
                            pending_logs = []
                            while logs:
                                pending_logs.append({'level': 'info', 'message': logs.popleft()})
                            reply = self.client.request('heartbeat', **lease, stage='running',
                                                        metrics=metrics, logs=pending_logs, capacity=host_capacity())
                            if reply.get('cancelRequested') is True:
                                cancel_requested.set()
                                return
                        except (WorkerError, ValueError, OSError, urllib.error.URLError):
                            monitor_failed.set()
                            cancel_requested.set()
                            return

                monitor = threading.Thread(target=monitor_job, name='re-lease-heartbeat', daemon=True)
                monitor.start()

                output, error, status = bounded_process(['docker', 'start', '--attach', name], timeout,
                                                        limit=MAX_RESULT, cancel=lambda: STOP.is_set() or cancel_requested.is_set(),
                                                        on_stderr=lambda data: logs.append(sanitized_log(data)))
                monitor_stop.set()
                monitor.join(timeout=30)
                if monitor_failed.is_set():
                    raise WorkerError('lease_lost', 'Worker could not maintain its execution lease.')
                inspect = json.loads(docker_command(['docker', 'inspect', '--format', '{{json .State}}', name]))
                if inspect.get('OOMKilled'):
                    raise WorkerError('memory_limit', 'Analysis reached the enforced memory limit.')
                if status or inspect.get('ExitCode') != 0:
                    raise WorkerError('tool_failure', 'Engine failed to complete static analysis.')
                result = json.loads(output)
                if result.get('engineId') != engine:
                    raise WorkerError('invalid_result', 'Engine returned a mismatched result identity.')
                if observed_memory:
                    result.setdefault('metrics', {})['memoryMb'] = observed_memory
                # Observed samples are a lower bound for peak usage, not a benchmark.
                result.setdefault('limitations', []).append('Memory usage is sampled every ten seconds; the instantaneous true peak may be higher.')
                if logs:
                    self.client.request('heartbeat', **lease, stage='running', metrics={},
                                        logs=[{'level': 'info', 'message': line} for line in logs])
                if result.get('engineVersion') != job.get('expectedEngineVersion'):
                    raise WorkerError('engine_unavailable', 'The result version differs from the verified lease.')
                outcome = dict(action='complete', result=result)
        except (WorkerError, ValueError, OSError, urllib.error.URLError, KeyError) as error:
            code, retryable = ('LEASE_LOST', False) if monitor_failed.is_set() else classify_failure(error, stage)
            # No blind analysis retries. Queue may retry only a separately classified
            # infrastructure fault with its existing bounded retry policy.
            outcome = dict(action='fail', code=code,
                           message='Artifact transfer was temporarily unavailable.' if retryable else 'Analysis could not complete. Review the diagnostic code; no success result was published.',
                           retryable=retryable)
        finally:
            monitor_stop.set()
            if create_attempted:
                try:
                    cleanup_container(name)
                except WorkerError:
                    STOP.set()
                    outcome = dict(action='fail', code='CLEANUP_FAILED', message='Worker cleanup could not be verified; worker stopped.', retryable=False)
            if monitor:
                monitor.join(timeout=30)
        if outcome:
            action = outcome.pop('action')
            self.client.request(action, **lease, **outcome)

    def run(self, once=False):
        self.recover()
        failures = 0
        while not STOP.is_set():
            try:
                records = self.health()
                reply = self.client.request('claim', workerId=self.worker_id, engines=records, capacity=host_capacity())
                if reply.get('job'):
                    self.execute(reply)
                failures = 0
            except (WorkerError, OSError, ValueError, urllib.error.URLError) as error:
                failures += 1
                # Circuit opens after three failures. No secrets/URLs/raw diagnostics.
                print(json.dumps({'event': 'worker_control_failure', 'count': failures,
                                  'code': error.code if isinstance(error, WorkerError) else 'network_or_control_failure'}), file=sys.stderr)
                if failures >= 3:
                    STOP.wait(min(60, 5 * 2 ** min(failures, 4)) + random.random() * 3)
            if once:
                break
            STOP.wait(15 + random.random() * 3)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--config', type=Path, default=Path(__file__).with_name('engines.json'))
    parser.add_argument('--once', action='store_true')
    args = parser.parse_args()
    if sys.platform != 'linux' or shutil.which('docker') is None:
        raise WorkerError('unsupported_host', 'A dedicated Linux Docker host is required; no tool will run on this host.')
    for signum in (signal.SIGTERM, signal.SIGINT):
        signal.signal(signum, lambda *_: STOP.set())
    Supervisor(args.config).run(args.once)


if __name__ == '__main__':
    try:
        main()
    except WorkerError as error:
        print(json.dumps({'error': error.code, 'message': str(error)}), file=sys.stderr)
        sys.exit(1)
