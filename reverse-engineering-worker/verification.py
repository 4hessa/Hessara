"""Read operator-owned real-analysis attestations; never treat --health as analysis."""
from __future__ import annotations

import hashlib
import io
import json
from pathlib import Path
import re
import time
import zipfile


def safe_sample() -> bytes:
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, 'w', compression=zipfile.ZIP_STORED) as archive:
        for name, content in (
            ('package.json', '{"name":"hessara-owned-safe-sample","version":"1.0.0","main":"index.js"}'),
            ('index.js', 'export function add(left, right) { return left + right; }\nexport const label = "HESSARA safe sample";\n'),
        ):
            entry = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
            entry.external_attr = 0o100644 << 16
            archive.writestr(entry, content)
    return stream.getvalue()


def load_verification(config: dict, engine: str, version: str | None = None) -> dict | None:
    """Reports are generated by verify_engine.py after real bounded execution.
    The report path belongs to the trusted operator's configuration, never an
    artifact. It is not a signature against a compromised administrator/worker.
    """
    if not config.get('verificationReport'):
        return None
    try:
        path = Path(config['verificationReport'])
        if not path.is_file() or path.stat().st_size > 8192:
            return None
        report = json.loads(path.read_text(encoding='utf-8'))
        if not isinstance(report, dict) or not isinstance(report.get('verification'), dict):
            return None
        proof = report['verification']
        expected = hashlib.sha256(safe_sample()).hexdigest()
        if (report.get('schemaVersion') != 1 or report.get('engineId') != engine
                or report.get('kind') != 'real-analysis-sample' or proof.get('passed') is not True
                or proof.get('imageDigest') != config.get('image')
                or not re.fullmatch(r'[a-zA-Z0-9./:_-]+@sha256:[a-f0-9]{64}', proof.get('imageDigest', ''))
                or not re.fullmatch(r'[a-f0-9]{64}', proof.get('artifactSha256', ''))
                or (engine == 'rea' and proof.get('artifactSha256') != expected)
                or report.get('assertionProfile') != engine + '-static-v1'
                or not isinstance(proof.get('engineVersion'), str) or not proof['engineVersion'].strip()
                or (version is not None and proof['engineVersion'] != version)
                or type(proof.get('verifiedAt')) is not int or not 0 < proof['verifiedAt'] <= int(time.time() * 1000)
                or not re.fullmatch(r'[a-f0-9]{64}', report.get('resultSha256', ''))):
            return None
        return {key: proof[key] for key in ('passed', 'imageDigest', 'engineVersion', 'artifactSha256', 'verifiedAt')}
    except (OSError, ValueError, TypeError, KeyError):
        return None


def assert_rea_sample(result: dict) -> None:
    if (result.get('engineId') != 'rea' or not isinstance(result.get('engineVersion'), str)
            or not result['engineVersion'].strip() or not result.get('findings') or not result.get('evidence')
            or 'index.js' not in json.dumps(result['evidence'], ensure_ascii=False)):
        raise ValueError('The real REA result did not contain the expected safe application evidence.')


def assert_sample(engine: str, result: dict, expected_name: str) -> None:
    if not isinstance(result, dict):
        raise ValueError('Expected structured analysis results.')
    if engine == 'rea':
        assert_rea_sample(result)
        return
    required = {'ghidra': 'functions', 'rizin': 'functions', 'radare2': 'functions',
                'angr': 'functions', 'jadx': 'files', 'mobsf': 'evidence'}
    if (engine not in required or result.get('engineId') != engine
            or not isinstance(result.get('engineVersion'), str) or not result['engineVersion'].strip()
            or not isinstance(result.get(required[engine]), list) or not result[required[engine]]
            or not result.get('evidence') or not expected_name
            or expected_name not in json.dumps(result, ensure_ascii=False)):
        raise ValueError('The real engine result did not contain the expected fixture evidence.')
